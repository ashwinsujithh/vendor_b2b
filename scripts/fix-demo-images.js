/* One-off fix-up: regenerate the demo product images (demo-*.svg) in place.
   Overwrites ONLY files that were generated by the demo seeder (demo-*.svg);
   real vendor uploads and the database rows are never touched.

   Usage: node scripts/fix-demo-images.js           (dry summary)
          node scripts/fix-demo-images.js --yes     (actually rewrite files)
*/
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const pool = require('../src/config/db');

const APPLY = process.argv.includes('--yes');
const UPLOAD_DIR = path.join(__dirname, '..', 'public', 'uploads', 'products');
const PALETTE = ['#159b69', '#2563eb', '#d97706', '#dc2626', '#7c3aed', '#0891b2'];

/* Same artwork as scripts/reset-demo-data.js makeImage() — kept in sync. */
function buildSvg(color, idx) {
  const shift = idx === 2 ? 95 : 0;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="480" height="480" viewBox="0 0 480 480">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${color}" stop-opacity=".18"/>
      <stop offset="1" stop-color="${color}" stop-opacity=".05"/>
    </linearGradient>
  </defs>
  <rect width="480" height="480" fill="url(#bg)"/>
  <circle cx="${150 + shift}" cy="${160 + (idx === 2 ? 20 : 0)}" r="118" fill="${color}" opacity=".16"/>
  <circle cx="${350 - shift}" cy="335" r="150" fill="${color}" opacity=".11"/>
  <circle cx="240" cy="${235 + (idx === 2 ? 25 : 0)}" r="84" fill="${color}" opacity=".32"/>
  <circle cx="240" cy="${235 + (idx === 2 ? 25 : 0)}" r="50" fill="${color}" opacity=".42"/>
</svg>`;
}

async function main() {
  const [rows] = await pool.query(
    `SELECT pi.img_id, pi.image_url, p.product, p.vendor_id
     FROM product_image pi JOIN product p ON p.product_id = pi.product_id
     WHERE pi.image_url LIKE '%/demo-%'
     ORDER BY pi.img_id`
  );

  if (!rows.length) {
    console.log('No demo images found — nothing to do.');
    process.exit(0);
  }

  console.log(`Found ${rows.length} demo image row(s). Mode: ${APPLY ? 'APPLY' : 'dry run (add --yes to write)'}`);
  let written = 0;
  let skipped = 0;

  for (const row of rows) {
    const file = String(row.image_url).split('/').pop();
    // Safety: only touch demo-generated SVGs.
    if (!/^demo-.+\.svg$/.test(file)) { skipped++; continue; }
    const fullPath = path.join(UPLOAD_DIR, file);
    if (!fs.existsSync(fullPath)) { console.log(`  ! missing on disk: ${file}`); skipped++; continue; }

    const idxMatch = file.match(/(\d+)\.svg$/);
    const idx = idxMatch ? Number(idxMatch[1]) : 1;
    const color = PALETTE[(Number(row.vendor_id) + Number(row.img_id)) % PALETTE.length];

    if (APPLY) {
      fs.writeFileSync(fullPath, buildSvg(color, idx));
      written++;
    } else {
      console.log(`  would rewrite ${file} (${row.product}, ${color}, variant ${idx})`);
    }
  }

  console.log(APPLY ? `Done — rewrote ${written} file(s), skipped ${skipped}.` : `Dry run complete — ${rows.length} row(s) eligible, ${skipped} skipped.`);
  process.exit(0);
}

main().catch((err) => { console.error('fix-demo-images failed:', err.message); process.exit(1); });
